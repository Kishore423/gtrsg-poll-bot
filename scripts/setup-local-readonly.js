// Builds a local-only configuration. The server sets its single Supabase session
// to read-only before any repository query, and rejects unsafe HTTP methods.
const fs = require('fs');
const path = require('path');
const postgres = require('postgres');

require('dotenv').config({ quiet: true });

const LEGACY_ROLE = 'gtrsg_local_readonly';

async function main() {
  if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is required in .env.');
  const sql = postgres(process.env.DATABASE_URL, { ssl: 'require', max: 1 });

  try {
    // Remove the short-lived role created by an earlier setup attempt. It was
    // unable to read RLS-protected production rows and is not used by this mode.
    const [existing] = await sql`select 1 from pg_roles where rolname = ${LEGACY_ROLE}`;
    if (existing) {
      await sql`revoke all privileges on all tables in schema public from ${sql(LEGACY_ROLE)}`;
      await sql`revoke usage on schema public from ${sql(LEGACY_ROLE)}`;
      await sql`revoke connect on database ${sql(new URL(process.env.DATABASE_URL).pathname.slice(1))} from ${sql(LEGACY_ROLE)}`;
      await sql`drop role ${sql(LEGACY_ROLE)}`;
    }

    const readOnlyUrl = new URL(process.env.DATABASE_URL);
    const envFile = path.join(process.cwd(), '.env.readonly');
    fs.writeFileSync(envFile, [
      '# Generated by npm run setup:local-readonly. Do not commit this file.',
      'LOCAL_READ_ONLY=true',
      `LOCAL_READONLY_DATABASE_URL=${readOnlyUrl.toString()}`,
      'APP_URL=http://localhost:3001',
      'PORT=3001',
      '',
    ].join('\n'), { mode: 0o600 });
    console.log('Created .env.readonly for the local read-only server.');
  } finally {
    await sql.end();
  }
}

main().catch((error) => {
  console.error('Failed to configure local read-only access:', error.message);
  process.exitCode = 1;
});
